/**
 * 궁합 초대 카드 후킹 문장 — 일간 10 × 상대(배우자성) 오행 5 = 50 템플릿. LLM 안 씀 (결정).
 *
 * 배우자성: 남자 = 재성(일간이 극하는 오행), 여자 = 관성(일간을 극하는 오행).
 * 카드에는 초대한 사람의 일간 성향 + "이 사람이 끌리는 상대의 기운" 을 한 줄로 쓴다.
 * 이름·생년월일은 절대 넣지 않는다.
 */
import { STEM_DATA, CONTROLS, type Stem, type Element } from './constants';

/** 일간·성별 → 배우자성 오행 */
export function spouseElement(stem: Stem, sex: 'male' | 'female'): Element {
  const el = STEM_DATA[stem].element;
  if (sex === 'male') return CONTROLS[el];
  // 나를 극하는 오행 = CONTROLS 의 역방향
  return (Object.keys(CONTROLS) as Element[]).find(k => CONTROLS[k] === el)!;
}

