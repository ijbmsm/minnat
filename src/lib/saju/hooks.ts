const EL_HANJA: Record<Element, string> = { 목: '木', 화: '火', 토: '土', 금: '金', 수: '水' };

export interface InviteHook {
  /** 일주 한자 (예: 丙戌) */
  dayPillarHanja: string;
  /** 일간 키워드 1개 */
  keyword: string;
  /** 후킹 한 줄 */
  line: string;
  /** 상대 기운 라벨 (예: 木) */
  partnerElement: Element;
  partnerElementHanja: string;
}

export function buildInviteHook(args: { stem: Stem; branchHanja: string; sex: 'male' | 'female'; keyword: string }): InviteHook {
  const partner = spouseElement(args.stem, args.sex);
  return {
    dayPillarHanja: `${STEM_DATA[args.stem].hanja}${args.branchHanja}`,
    keyword: args.keyword,
    line: INVITE_HOOKS[args.stem][partner],
    partnerElement: partner,
    partnerElementHanja: EL_HANJA[partner],
  };
}
